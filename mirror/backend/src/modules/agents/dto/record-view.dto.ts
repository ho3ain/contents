import { ApiPropertyOptional } from '@nestjs/swagger';
import {
  ArrayMaxSize,
  ArrayMinSize,
  IsArray,
  IsOptional,
  IsString,
  IsUUID,
  Matches,
  MaxLength,
} from 'class-validator';

/** Phase A4 — product-page view beacon payload (all optional). */
export class RecordViewDto {
  @ApiPropertyOptional({
    description: 'Anonymous random visitor id (UUID) generated by the browser',
  })
  @IsOptional()
  @IsUUID()
  visitorId?: string;

  @ApiPropertyOptional({
    description: 'Traffic source (share channel / utm_source), normalized',
  })
  @IsOptional()
  @IsString()
  @MaxLength(32)
  source?: string;

  @ApiPropertyOptional({
    description:
      'A5 §9 — the sponsored placement the visitor came from (validated: only an ACTIVE promotion of this product is attributed)',
  })
  @IsOptional()
  @IsUUID()
  promotionId?: string;
}

/** A5 §23 — listing cards shown in a marketplace list (beacon). */
export class RecordImpressionsDto {
  @IsArray()
  @ArrayMinSize(1)
  @ArrayMaxSize(48)
  @IsString({ each: true })
  @Matches(/^[a-z0-9-]{1,160}$/i, { each: true })
  slugs: string[];

  @IsOptional()
  @IsUUID()
  visitorId?: string;

  @IsOptional()
  @IsString()
  @MaxLength(32)
  source?: string;
}

/** A5 §9 — sponsored card impression / click beacon. */
export class PromotionEventDto {
  @IsOptional()
  @IsUUID()
  visitorId?: string;
}
