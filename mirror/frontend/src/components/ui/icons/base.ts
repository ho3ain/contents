/**
 * MESH icon system — base (conventional) icon catalogue.
 *
 * Source: Lucide, consumed through the already-installed `react-icons/lu`
 * pack (ISC licence, attribution in docs/icon-system/MESH-ICON-SYSTEM.md).
 * Lucide is the maintained successor of Feather (which the shell used
 * before): identical 24-px grid, 2-px round strokes — so swapping packs
 * changes no glyph that was already on screen, and closes the gaps that
 * produced wrong or missing icons (megaphone → target, headphones → null).
 *
 * Naming is SEMANTIC and stable: a name describes the meaning in MESH, not
 * the Lucide glyph. Rename the glyph behind a name; never rename the name.
 *
 * Direction: names ending in `Start`/`End`/`Back`/`Forward` are LOGICAL — the
 * component mirrors them in RTL (CSS, no JS). Physical names (`arrowLeft`,
 * `chevronRight`, …) never mirror. See `DIRECTIONAL`.
 */
